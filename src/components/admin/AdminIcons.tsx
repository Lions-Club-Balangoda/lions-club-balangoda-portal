export function AdminNavIcon({
  icon,
  className = 'w-5 h-5',
}: {
  icon: string;
  className?: string;
}) {
  switch (icon) {
    case 'dashboard':
      return <DashboardIcon className={className} />;
    case 'projects':
      return <ProjectsIcon className={className} />;
    case 'news':
      return <NewsIcon className={className} />;
    case 'board':
      return <BoardIcon className={className} />;
    case 'media':
      return <MediaIcon className={className} />;
    case 'submissions':
      return <SubmissionsIcon className={className} />;
    case 'users':
      return <UsersIcon className={className} />;
    default:
      return <DashboardIcon className={className} />;
  }
}

